"""Numbers derived from the fix-experiment summaries.

python -m locbench.fix_derived  ->  experiments/05_find_vs_fix/fix_derived.md
"""
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
EXP = os.path.join(ROOT, "experiments", "05_find_vs_fix")
MODELS = ["e2b", "e4b", "12b"]


def holm(pvals: dict) -> dict:
    order = sorted(pvals, key=pvals.get)
    out, running = {}, 0.0
    for i, k in enumerate(order):
        running = max(running, min(1.0, (len(order) - i) * pvals[k]))
        out[k] = running
    return out


def main() -> None:
    lines = ["# Fix experiment: derived numbers", "",
             "Generated by `python -m locbench.fix_derived` from `fix_{e2b,e4b,12b}_summary.json`.", "",
             "## Holm correction over H8a–H8d within each model (alpha = 0.05)", "",
             "| model | test | diff (pts) | gained vs lost | exact McNemar p | Holm-adjusted p | holds |",
             "|---|---|---|---|---|---|---|"]
    not_edits = resolved_without = 0
    cells, calls = [], {}
    for m in MODELS:
        s = json.load(open(os.path.join(EXP, f"fix_{m}_summary.json")))
        tests = s["tests"]
        adj = holm({k: v["p_exact_mcnemar"] for k, v in tests.items()})
        for k in sorted(tests):
            t = tests[k]
            lines.append(f"| {m.upper()} | {k} | {100 * t['diff']:+.1f} | {t['a_only']} vs {t['b_only']} | "
                         f"{t['p_exact_mcnemar']:.4f} | {adj[k]:.4f} | {'yes' if adj[k] < 0.05 else 'no'} |")
        for cond, d in s["exploratory"]["decomposition"].items():
            f = d["function"]
            not_edits += f["not_edits"]
            resolved_without += f["resolved_if_not"]
            cells.append((m.upper(), cond, f["edits_gold"], f["resolved_if_edits"]))
        calls[m.upper()] = {c: v["mean_tool_calls"] for c, v in s["conditions"].items()}

    lines += ["", "## Find × fix decomposition (73 tasks with function-level gold)", "",
              f"Resolved although the final patch edits no gold function: {resolved_without} of {not_edits} "
              "model × condition × task cases.", "",
              "| model | condition | patch edits a gold function | resolved when it does |", "|---|---|---|---|"]
    lines += [f"| {m} | {c} | {n} | {r}/{n} ({100 * r / n:.0f}%) |" for m, c, n, r in cells]
    sizes = [n for _, _, n, _ in cells]
    lines += ["", f"Cell sizes range from {min(sizes)} to {max(sizes)} tasks.", "",
              "## Mean tool calls per episode (86 tasks)", "", "| model | " + " | ".join(calls["E2B"]) + " |",
              "|---|" + "---|" * len(calls["E2B"])]
    lines += [f"| {m} | " + " | ".join(f"{v:.1f}" for v in c.values()) + " |" for m, c in calls.items()]
    out = os.path.join(EXP, "fix_derived.md")
    open(out, "w").write("\n".join(lines) + "\n")
    print("wrote", out)


if __name__ == "__main__":
    main()
